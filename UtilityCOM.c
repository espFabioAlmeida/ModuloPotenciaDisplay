/*==============================================================================
LIMPA STRING
==============================================================================*/
void limpaBufferUart() {
   for(unsigned int i = 0; i < BUFFER_MODBUS_SIZE; i ++) {
      bufferModbus[i] = 0x00; 
   }

   contUartBuffer = 0;
}
/*==============================================================================
INTERRUPCAO RDA
==============================================================================*/
#INT_RDA
void rda() { 
   if(kbhit()) {
      char dado = getch();
      uartBuffer[contUartBuffer] = dado;
      
      contUartBuffer ++;
      if(contUartBuffer >= BUFFER_MODBUS_SIZE) {
         limpaBufferUart();
      }
      
   }
}
